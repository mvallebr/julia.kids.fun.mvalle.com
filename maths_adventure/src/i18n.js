export function uiText(language, key, vars = {}) {
  let value = COPY[language]?.[key] ?? COPY.pt[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, replacement);
  return value;
}

// Campo bilíngue { pt, en } -> string no idioma ativo (cade em pt).
export function lang(value, language) {
  if (typeof value === 'string') return value;
  return value?.[language] ?? value?.pt ?? '';
}
